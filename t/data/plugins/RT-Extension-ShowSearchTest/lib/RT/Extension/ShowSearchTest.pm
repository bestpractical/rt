=head1 NAME

RT::Extension::ShowSearchTest - Test plugin for ShowSearch short code testing

=head1 DESCRIPTION

This test plugin provides Mason templates for testing the ShowSearch component
with short code (sc) parameters. It is used by the test suite to verify that
ShowSearch can display searches loaded via RT's URL shortener.

=cut
